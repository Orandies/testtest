"""Вырезание секретов из текста перед записью в логи и журнал аудита.

Работает в два слоя: известные значения секретов вырезаются дословно, а
типовые формы записи секретов ловятся по шаблонам — на случай значений,
о которых агент не знает.
"""

from __future__ import annotations

import re

MASK = "***REDACTED***"

# Bearer и Basic обрабатываются первыми: иначе шаблон «ключ-значение»
# закрыл бы слово Bearer, а сам токен остался бы в тексте.
_BEARER = re.compile(r"(?i)\bbearer\s+[a-z0-9._~+/=-]+")
_BASIC = re.compile(r"(?i)\bbasic\s+[a-z0-9+/=]+")
_KEY_VALUE = re.compile(
    r"""(?i)\b(token|secret|password|passwd|api[_-]?key|authorization|cookie)\b
        (["']?\s*[:=]\s*)
        (["']?)([^\s"',;]+)""",
    re.VERBOSE,
)


class Redactor:
    """Вырезает секреты из текста до того, как он попадёт в журнал.

    Работает в два слоя, потому что одного мало. Первый — известные
    значения: токены из конфигурации вырезаются дословно. Второй — типовые
    формы записи: token=..., Authorization: Bearer ... и подобные ловятся
    шаблонами, даже когда конкретное значение агенту неизвестно. Так
    секрет из чужого конфига или из ответа внешней системы тоже не
    попадёт в лог.

    Известные значения обрабатываются от длинного к короткому: иначе
    короткий секрет, оказавшийся частью длинного, разорвал бы длинный на
    куски и остаток ушёл бы в журнал открытым текстом.
    """

    def __init__(self, known_secrets: tuple[str, ...] = ()) -> None:
        # Длинные значения обрабатываются первыми, чтобы короткое не
        # разорвало длинное на части.
        self._known = tuple(sorted((s for s in known_secrets if s), key=len, reverse=True))

    def redact(self, text: str) -> str:
        # Известные значения вырезаются дословно.
        for secret in self._known:
            text = text.replace(secret, MASK)
        # Затем типовые формы записи секретов.
        text = _BEARER.sub(MASK, text)
        text = _BASIC.sub(MASK, text)
        text = _KEY_VALUE.sub(rf"\1\2\3{MASK}", text)
        return text
